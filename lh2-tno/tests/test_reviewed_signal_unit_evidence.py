import json
from pathlib import Path

from lh2_tno.reviewed_signal_unit_evidence import audit_reviewed_signal_unit_evidence


def _map(document_hash: str):
    return {
        "source_evidence": {"sha256": document_hash},
        "signal_units": {
            "PT-1": {
                "unit": "bar",
                "quantity": "pressure",
                "pressure_basis": "unresolved",
                "evidence": [{"page": 1, "anchor": "PT-1", "context": "1 bar"}],
            },
            "TT-1": {
                "unit": "degC",
                "quantity": "temperature",
                "evidence": [{"page": 1, "anchor": "TT-1", "context": "-50°C"}],
            },
        },
    }


def test_document_anchors_and_partial_header_coverage_are_explicit(tmp_path: Path):
    document = tmp_path / "procedure.pdf"
    document.write_bytes(b"not a pdf")
    # Patch the PDF reader through a minimal fake is not desirable here; use a
    # real one-page PDF generated by pypdf's writer.
    from pypdf import PdfWriter

    writer = PdfWriter()
    writer.add_blank_page(width=72, height=72)
    with document.open("wb") as handle:
        writer.write(handle)
    # A blank PDF has no text, so verify the fail-closed path instead.
    report = audit_reviewed_signal_unit_evidence(
        _map("bad"),
        source_document=document,
        timeseries_audit={"files": [{"sheets": [{"headers": ["PT-1", "TT-1", "DPT-1"]}]}]},
    )
    assert report["status"] == "REVIEWED_SIGNAL_UNIT_EVIDENCE_BLOCKED"
    assert report["source_document_digest_match"] is False
    assert report["promotion_gates"]["state_snapshot_binding_allowed"] is False


def test_reviewed_anchor_map_can_be_checked_without_frequency_or_state_promotion(tmp_path: Path, monkeypatch):
    document = tmp_path / "procedure.pdf"
    document.write_bytes(b"placeholder")
    import lh2_tno.reviewed_signal_unit_evidence as module

    monkeypatch.setattr(module, "_decode_pdf_pages", lambda path: ["PT-1 pressure 1 bar; TT-1 temperature -50°C"])
    digest = module._sha256(document)
    report = audit_reviewed_signal_unit_evidence(
        _map(digest),
        source_document=document,
        timeseries_audit={"files": [{"sheets": [{"headers": ["PT-1", "TT-1", "DPT-1"]}]}]},
    )
    assert report["status"] == "REVIEWED_SIGNAL_UNIT_EVIDENCE_PARTIAL"
    assert report["reviewed_signal_count"] == 2
    assert report["observed_unmapped_tags"] == ["DPT1"]
    assert report["policy"]["pressure_basis_inference_performed"] is False


def test_source_and_comparison_units_are_reported_as_separate_roles(tmp_path: Path, monkeypatch):
    document = tmp_path / "procedure.pdf"
    document.write_bytes(b"placeholder")
    import lh2_tno.reviewed_signal_unit_evidence as module

    monkeypatch.setattr(module, "_decode_pdf_pages", lambda path: ["PT-1 raw MPa; setpoint 6 bar"])
    digest = module._sha256(document)
    report = audit_reviewed_signal_unit_evidence(
        {
            "source_evidence": {"sha256": digest},
            "signal_units": {
                "PT-1": {
                    "source_unit": "MPa",
                    "comparison_unit": "bar",
                    "quantity": "pressure",
                    "pressure_basis": "unresolved",
                    "evidence": [{"page": 1, "anchor": "PT-1"}],
                }
            },
        },
        source_document=document,
        timeseries_audit={"files": [{"sheets": [{"headers": ["PT-1"]}]}]},
    )
    assert report["status"] == "REVIEWED_SIGNAL_UNIT_EVIDENCE_COMPLETE"
    signal = report["signals"][0]
    assert signal["source_unit"] == "MPa"
    assert signal["comparison_unit"] == "bar"
    assert report["policy"]["comparison_unit_used_for_runtime_conversion"] is False
