"""Flatten a facility evidence request into an actionable provider worklist.

The worklist is an intake aid, not a risk result.  It preserves the exact
event/component/port identity and the evidence requirements generated by the
facility assessment.  Missing evidence remains missing; no frequency,
consequence, or facility-QRA value is inferred here.
"""
from __future__ import annotations

from collections import Counter, defaultdict
from collections.abc import Mapping, Sequence
from typing import Any


SCHEMA = "prism.facility_evidence_worklist.v1"


def _seq(value: Any) -> tuple[Any, ...]:
    if isinstance(value, Sequence) and not isinstance(value, (str, bytes)):
        return tuple(value)
    return ()


def _strings(value: Any) -> list[str]:
    return [str(item) for item in _seq(value) if str(item).strip()]


def _case_row(request: Mapping[str, Any], index: int) -> dict[str, Any]:
    exact = request.get("exact_match_required")
    exact = exact if isinstance(exact, Mapping) else {}
    boundary = request.get("current_release_boundary")
    boundary = boundary if isinstance(boundary, Mapping) else {}
    return {
        "sequence": index + 1,
        "request_id": request.get("request_id") or f"case-{index + 1}",
        "event_id": request.get("event_id"),
        "component_id": request.get("component_id"),
        "asset_id": request.get("asset_id"),
        "release_branch_id": request.get("release_branch_id"),
        "annual_condition_id": request.get("annual_condition_id"),
        "scenario_families": sorted(set(_strings(request.get("scenario_families")))),
        "current_status": request.get("current_status"),
        "gap_class": request.get("gap_class"),
        "request_kind": request.get("request_kind"),
        "qualification_required": request.get("qualification_required") is True,
        "required_input_origin": request.get("required_input_origin"),
        "exact_identity": {
            "event_id": exact.get("event_id", request.get("event_id")),
            "component_id": exact.get("component_id", request.get("component_id")),
            "port_ids": _strings(exact.get("port_ids", request.get("provider_packet_port_ids"))),
            "provider_source_digests": _strings(exact.get("provider_source_digests")),
            "provider_result_digests": _strings(exact.get("provider_result_digests")),
        },
        "release_boundary": {
            "termination_basis": boundary.get("termination_basis"),
            "termination_time_s": boundary.get("termination_time_s"),
            "termination_provenance": boundary.get("termination_provenance"),
            "strict_termination_basis_allowed": boundary.get("strict_termination_basis_allowed"),
            "domain_truncated": boundary.get("domain_truncated"),
            "inventory_outside_domain": boundary.get("inventory_outside_domain"),
        },
        "required_provider_evidence": _strings(request.get("required_provider_evidence")),
        "blocking_reasons": _strings(request.get("blocking_reasons")),
    }


def build_facility_evidence_worklist(request_document: Mapping[str, Any]) -> dict[str, Any]:
    """Return a deterministic, provider-facing view of a facility request."""
    if not isinstance(request_document, Mapping):
        raise ValueError("request_document must be an object")
    raw_cases = request_document.get("case_requests", ())
    if not isinstance(raw_cases, Sequence) or isinstance(raw_cases, (str, bytes)):
        raise ValueError("request_document.case_requests must be an array")
    if any(not isinstance(row, Mapping) for row in raw_cases):
        raise ValueError("every case request must be an object")

    cases = [_case_row(row, index) for index, row in enumerate(raw_cases)]
    by_component: dict[str, list[dict[str, Any]]] = defaultdict(list)
    by_family: dict[str, list[dict[str, Any]]] = defaultdict(list)
    gate_counts: Counter[str] = Counter()
    for row in cases:
        component = str(row["component_id"] or "<missing-component>")
        by_component[component].append(row)
        families = row["scenario_families"] or ["<undeclared-family>"]
        for family in families:
            by_family[family].append(row)
        for reason in row["blocking_reasons"]:
            gate_counts[reason] += 1

    def _summary(groups: Mapping[str, list[dict[str, Any]]]) -> list[dict[str, Any]]:
        output = []
        for key in sorted(groups):
            rows = groups[key]
            output.append({
                "key": key,
                "case_count": len(rows),
                "request_ids": [row["request_id"] for row in rows],
                "event_ids": sorted({str(row["event_id"]) for row in rows if row["event_id"]}),
                "required_input_origins": sorted({
                    str(row["required_input_origin"])
                    for row in rows if row["required_input_origin"]
                }),
                "required_evidence": sorted({
                    item for row in rows for item in row["required_provider_evidence"]
                }),
                "blocking_reasons": sorted({
                    item for row in rows for item in row["blocking_reasons"]
                }),
            })
        return output

    current = request_document.get("current_assessment")
    current = dict(current) if isinstance(current, Mapping) else {}
    return {
        "schema_version": SCHEMA,
        "status": "OPEN_PROVIDER_EVIDENCE_WORKLIST" if cases else "EMPTY_PROVIDER_EVIDENCE_WORKLIST",
        "facility_id": request_document.get("facility_id"),
        "scope": request_document.get("scope"),
        "source_request_schema": request_document.get("schema_version"),
        "promotion_policy": {
            "frequency_is_not_assigned": True,
            "sensor_frequency_learning": False,
            "missing_evidence_is_not_zero_risk": True,
            "facility_qra_promotion": False,
        },
        "current_assessment": {
            key: current.get(key)
            for key in (
                "event_count", "case_count", "strict_uncomputed_case_count",
                "qualified_provider_packet_case_count", "facility_total_risk_available",
                "qualified_facility_qra_available", "facility_promotion_allowed_now",
            )
            if key in current
        },
        "case_count": len(cases),
        "case_rows": cases,
        "component_summary": _summary(by_component),
        "family_summary": _summary(by_family),
        "blocking_reason_counts": dict(sorted(gate_counts.items())),
    }


__all__ = ["SCHEMA", "build_facility_evidence_worklist"]
