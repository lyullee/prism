#!/usr/bin/env python3
"""Generate the human-readable results register from results.json."""

from __future__ import annotations

import json
import math
from collections import Counter
from pathlib import Path


SECTIONS = {
    "6B": "Purple Book Appendix 6.B",
    "10": "Red Book 10.4",
    "source": "Source term",
    "transient": "Time-dependent release",
    "fire": "Fire: flame length, radiation, transmissivity",
    "fireball": "Fireball",
    "spill": "Ignited LH2 spill",
    "blast": "Blast wave",
    "fragments": "Fragments",
    "eqdamage": "Equipment damage criteria",
    "height": "Release height",
    "indoor": "Indoor accumulation",
    "dispersion": "GH2 dispersion",
    "cold": "Cold hydrogen routing",
    "fig5": "Purple Book damage figures",
    "freq": "Frequency library",
    "ignition": "Ignition",
    "gating": "Gating experiment",
    "hiad": "HIAD incident database",
    "incident": "Incident comparison",
    "validation": "External validation",
    "crosscheck": "Implementation versus model choice",
    "sens": "Sensitivity",
    "e2e": "End to end",
}


def _format(value) -> str:
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError(f"non-finite registered result: {value!r}")
        return f"{value:.4g}"
    return str(value).replace("|", "\\|")


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    source = root / "results.json"
    target = root / "핸드오프" / "12_RESULTS_REGISTER.md"
    payload = json.loads(source.read_text(encoding="utf-8"))
    results = payload["results"]
    if payload["n_results"] != len(results):
        raise ValueError("results.json count does not match its contents")

    counts = Counter(item["grade"] for item in results.values())
    lines = [
        "# 12 — Results register",
        "",
        f"All {len(results)} registered results, generated by `reproduce.py` ",
        "and checked for drift by `reproduce.py --check`. This file is ",
        "generated by `gen_results_register.py`; do not edit it by hand.",
        "",
        "Audit status: engineering screening only. Numerical agreement and ",
        "software-measured values are not independent physical experiments. ",
        "Facility acceptance and a runtime-integrated dual-evidence claim ",
        "gate remain withheld; see `26_AUDIT_FIX_STATUS_20260831.md`.",
        "",
        "| grade | count |",
        "|---|---:|",
    ]
    for grade in ("PUBLISHED_VALIDATED", "MEASURED",
                  "PUBLISHED_UNVALIDATED", "ENGINEERING_JUDGEMENT",
                  "PLACEHOLDER"):
        if counts[grade]:
            lines.append(f"| {grade} | {counts[grade]} |")

    grouped: dict[str, list[tuple[str, dict]]] = {
        prefix: [] for prefix in SECTIONS
    }
    for key, item in results.items():
        prefix = key.split(".", 1)[0]
        if prefix not in grouped:
            raise ValueError(f"no register section for result {key!r}")
        grouped[prefix].append((key, item))

    for prefix, title in SECTIONS.items():
        rows = sorted(grouped[prefix])
        if not rows:
            continue
        lines += ["", "---", "", f"## {title}", "",
                  "| key | value | grade |", "|---|---:|---|"]
        for key, item in rows:
            lines.append(
                f"| `{key}` | {_format(item['value'])} | {item['grade']} |")
        lines += ["", "<details><summary>what each is evidence for</summary>", ""]
        for key, item in rows:
            claim = str(item["claim"]).replace("|", "\\|")
            lines.append(f"- **`{key}`** — {claim}")
        lines += ["", "</details>"]

    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target}: {len(results)} results")


if __name__ == "__main__":
    main()
